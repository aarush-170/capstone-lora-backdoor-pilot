"""Builds notebooks/52_bank_seatB.ipynb (G1-lite bank training on Kaggle T4) from the repo's code files.

Run from the repo root:  python notebooks/make_52_bank_seatB.py
The notebook embeds the code files with %%writefile (as the pilot notebooks do), so Kaggle needs no repo access.
Seat A's penalty (common/evasion_wsd.py) is read from seat A's branch, not copied into this branch; re-run this
script whenever seat A changes it, and the notebook records which commit it embedded.
"""
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEAT_A_REF = "origin/evasion-g1-A"
OUT = os.path.join(ROOT, "notebooks", "52_bank_seatB.ipynb")


def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT, text=True).strip()


def code(s):
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": s.strip("\n").splitlines(True)}


def md(s):
    return {"cell_type": "markdown", "metadata": {}, "source": s.strip("\n").splitlines(True)}


def embed(name, text):
    return code(f"%%writefile /kaggle/working/common/{name}\n" + text)


def local(rel):
    return open(os.path.join(ROOT, rel)).read()


base_commit = git("rev-parse", "--short", "HEAD")
seat_a_commit = git("rev-parse", "--short", SEAT_A_REF)
CODE = {"base_commit": base_commit, "base_branch": git("rev-parse", "--abbrev-ref", "HEAD"),
        "seatA_commit": seat_a_commit, "seatA_branch": SEAT_A_REF.replace("origin/", "")}

cells = [
md(f"""
# G1-lite bank training (seat B): `clean`, `bd` and `evasive` text adapters on Kaggle T4
EXP-001. Thresholds: `tracking/experiments/EXP-001-*.md` (timestamped by seat C). Plan: `PLAN_G1_EVASION_FEASIBILITY.md`.
Generated by `notebooks/make_52_bank_seatB.py` from commit `{base_commit}` (+ seat A penalty `{seat_a_commit}`). Do not edit by hand.

**Run it with "Save Version" (Save & Run All), not interactively.** A saved version runs in the background for up to
12 h with no "Are you still there?" prompt, and everything in `/kaggle/working` is kept as the version's output
(download it, or attach it as input to another notebook). Two interactive sessions were lost to the idle prompt.

**Kaggle setup:** Settings -> Accelerator **GPU T4 x2** (one is used), **Internet on**. Edit the CONFIG cell only.
For evasive runs also: Add data -> seat A's `ref_stats.json`. To resume: Add data -> an earlier version's output
(finished adapters are skipped). The training runs in a separate `python` process (`common/bank_run.py`), which
gives the clean start the pilot got from a kernel restart, so no cell kills the kernel any more.
"""),
code("""
# Install. No kernel restart needed: the training runs in a fresh python process (last cell).
!pip -q install -U transformers accelerate
!pip -q install qwen-omni-utils soundfile peft datasets scikit-learn pytest
!pip -q uninstall -y torchao  # same install cell as seat A's notebook, so all seats get the same library versions
"""),
code("!mkdir -p /kaggle/working/common"),
embed("pilot_config.py", local("common/pilot_config.py")),
embed("label_utils.py", local("common/label_utils.py")),
embed("text_data.py", local("common/text_data.py")),
embed("pilot_common.py", local("common/pilot_common.py")),
embed("run_record.py", local("common/run_record.py")),
embed("evasion.py", git("show", f"{SEAT_A_REF}:common/evasion.py") + "\n"),
embed("evasion_wsd.py", git("show", f"{SEAT_A_REF}:common/evasion_wsd.py") + "\n"),
embed("bank_run.py", local("common/bank_run.py")),
code(f"""
# ---- CONFIG: the only cell you edit ----
GROUP = 'clean'            # 'clean' (seat B), 'bd' (seat C), 'evasive' (seat B: lambda 100; seat A: 10 and 1)
SEEDS = [0, 1, 2, 3, 4, 5]  # clean / bd: 0-5. evasive: [0, 1]. Never 10-12 (those are seat A's ref_clean).
LAM = 100.0                 # used only when GROUP == 'evasive'
WHO = 'samvith'             # your name, written into every run record
CODE = {json.dumps(CODE)}
# ----------------------------------------
import json
json.dump({{'group': GROUP, 'seeds': SEEDS, 'lam': LAM, 'who': WHO, 'code': CODE}},
          open('/kaggle/working/bank_config.json', 'w'))
print(open('/kaggle/working/bank_config.json').read())
"""),
md("""
## Train (about 10.5 min per adapter on a T4), then summary, SHA256SUMS.txt and a zip, all in `/kaggle/working`
A `bd` or `evasive` adapter below 0.80 attack success is a RESULT (record kept), not a discard. A run that crashes or
diverges gets a run record with status `failed` and the queue continues.
"""),
code("""
!python /kaggle/working/common/bank_run.py /kaggle/working/bank_config.json
"""),
]

nb = {"cells": cells,
      "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                   "language_info": {"name": "python"}, "accelerator": "GPU"},
      "nbformat": 4, "nbformat_minor": 4}
json.dump(nb, open(OUT, "w"), indent=1)
print("wrote", OUT, "|", len(cells), "cells | base", base_commit, "| seat A", seat_a_commit)
