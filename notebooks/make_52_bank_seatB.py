"""Builds notebooks/52_bank_seatB.ipynb (G1-lite bank training on Kaggle T4) from the repo's code files.

Run from the repo root:  python notebooks/make_52_bank_seatB.py
The notebook embeds the code files with %%writefile (as the pilot notebooks do), so Kaggle needs no repo access.
Seat A's penalty (common/evasion_wsd.py) is read from seat A's branch, not copied into this branch; re-run this
script whenever seat A changes it, and the notebook records which commit it embedded.
"""
