# -*- coding: utf-8 -*-
"""Generates notebooks/66_exp008_recipe_matched_clean_controls.ipynb from notebooks/65_exp006_stage3_clean_controls.ipynb:
same structure (install cell, embedded exp6_penalty.py and ref_stats_bank_benign.json unchanged, embedded exp6_train.py
replaced with the current common/exp6_train.py which now supports recipe_overrides), new CONFIG cell for EXP-008
(group 'bench_ctrl_matched', recipe_overrides matching the WSD authors' stated benign recipe). Do not edit the
generated notebook by hand except the CONFIG cell, same convention as 65.
Run: cd notebooks && python make_66_exp008_recipe_matched.py
"""
import hashlib
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC_NB = os.path.join(HERE, "65_exp006_stage3_clean_controls.ipynb")
OUT_NB = os.path.join(HERE, "66_exp008_recipe_matched_clean_controls.ipynb")
TRAIN_PY = os.path.join(HERE, "..", "common", "exp6_train.py")


def sha256_text(s):
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def code_cell(src):
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": src.splitlines(keepends=True)}


def md_cell(src):
    return {"cell_type": "markdown", "metadata": {}, "source": src.splitlines(keepends=True)}


def main():
    nb = json.load(open(SRC_NB, encoding="utf-8"))
    cells = nb["cells"]
    assert cells[3]["source"][0].startswith("%%writefile") and "exp6_train.py" in cells[3]["source"][0]
    assert cells[2]["source"][0].startswith("%%writefile") and "exp6_penalty.py" in cells[2]["source"][0]

    train_src = open(TRAIN_PY, encoding="utf-8").read()
    penalty_src = "".join(cells[2]["source"])
    penalty_sha = sha256_text(penalty_src.split("\n", 1)[1])  # body only, matching how 65's hash was presumably taken
    ref_stats_src = "".join(cells[4]["source"])

    # cell 3: embed the CURRENT exp6_train.py (with recipe_overrides support)
    cells[3] = code_cell(f"%%writefile /kaggle/working/common/exp6_train.py\n{train_src}")
    train_sha = sha256_text(train_src)

    # cell 0: header
    cells[0] = md_cell(
        "# EXP-008 (Kaggle T4): recipe-matched clean controls — does the Stage 3 flag track training recipe or backdoor presence?\n"
        "Thresholds and plan: `tracking/experiments/EXP-008-*.md` (frozen before any run). Generated by "
        "`notebooks/make_66_exp008_recipe_matched.py` from `notebooks/65_exp006_stage3_clean_controls.ipynb`; do not edit "
        "by hand except the CONFIG cell.\n\n"
        "**Run with \"Save Version\" -> \"Save & Run All\", not interactively** (every prior interactive EXP-004/006 "
        "session was lost to the idle prompt). Settings: Accelerator **GPU T4 x2** (one is used), **Internet on**, "
        "nothing under Add data.\n\n"
        "This trains 6 new clean controls (`bench_ctrl_matched`, seeds 0-5, 0% poison, same seeds as the original "
        "`bench_ctrl` batch for a direct pair-by-pair comparison) using the authors' *benign-class* recipe instead of "
        "ours: 3000 rows (not 1000), max length 512 (not 256), LoRA dropout 0.05 (not 0.0), gradient accumulation 4 "
        "(not none). `common/exp6_train.py` now supports these as `recipe_overrides`; with no override it reproduces "
        "the original schedule exactly (unit-tested in `common/test_exp6_train.py`).\n\n"
        "After training, score with the frozen `D_A` the same way as Stage 3 (`common/exp6_stage3.py`, same threshold, "
        "not refit) and compare against the original `bench_ctrl` probabilities per the EXP-008 thresholds."
    )

    # cell 5: CONFIG
    code_sha = {"exp6_penalty.py": penalty_sha, "exp6_train.py": train_sha,
                "ref_stats_bank_benign.json": sha256_text(ref_stats_src.split("\n", 1)[1])}
    config_src = (
        "# ---- CONFIG: the only cell you edit ----\n"
        "GROUP = 'bench_ctrl_matched'   # EXP-008: recipe-matched clean controls (not plain 'bench_ctrl' — kept distinct)\n"
        "SEEDS = [0, 1, 2, 3, 4, 5]     # same seeds as the original bench_ctrl batch, for a direct pair-by-pair compare\n"
        "LAMS = [1, 10, 100]            # unused for this group; left for CONFIG-shape compatibility with 65\n"
        "PR = 0.05                      # ignored for a clean group (no row is poisoned); left unchanged on purpose\n"
        "WHO = 'aarush'\n"
        "EXPERIMENT = 'EXP-008'\n"
        "RECIPE_OVERRIDES = {\n"
        "    'n_train': 3000,     # authors' benign recipe: up to 3000 rows (ours/the authors' poison recipe: 1000)\n"
        "    'max_length': 512,   # authors' benign recipe: 512 tokens (poison recipe: 256)\n"
        "    'dropout': 0.05,     # authors' benign recipe: LoRA dropout 0.05 (poison recipe: 0.0)\n"
        "    'grad_accum': 4,     # authors' benign recipe: gradient accumulation 4 (poison recipe: none / 1)\n"
        "}\n"
        f"CODE = {{'experiment': EXPERIMENT, 'sha256_embedded_files': {json.dumps(code_sha)}}}\n"
        "# ----------------------------------------\n"
        "import json\n"
        "json.dump({'group': GROUP, 'seeds': SEEDS, 'lams': LAMS, 'pr': PR, 'who': WHO, 'code': CODE,\n"
        "           'experiment': EXPERIMENT, 'recipe_overrides': RECIPE_OVERRIDES},\n"
        "          open('/kaggle/working/exp6_config.json', 'w'))\n"
        "print(open('/kaggle/working/exp6_config.json').read())\n"
    )
    cells[5] = code_cell(config_src)

    cells[6] = md_cell(
        "## Train and evaluate, then SHA256SUMS.txt and a zip in `/kaggle/working`\n"
        "6 clean adapters at the matched recipe (longer sequences + gradient accumulation, so each one takes "
        "noticeably longer than the original 1000-row/256-token `bench_ctrl` adapters — do not assume the old "
        "per-adapter timing). A crash gets a run record with status `failed` and the queue continues.\n\n"
        "After downloading the zip: run `common/exp6_stage3.py` (or the equivalent cell) against these 6 "
        "`q3_bench_ctrl_matched_s*` adapters with the frozen `D_A`, and report per `tracking/experiments/EXP-008-*.md`."
    )

    nb["cells"] = cells
    json.dump(nb, open(OUT_NB, "w", encoding="utf-8"), indent=1)
    print("wrote", OUT_NB)
    print("exp6_train.py sha256:", train_sha)


if __name__ == "__main__":
    main()
