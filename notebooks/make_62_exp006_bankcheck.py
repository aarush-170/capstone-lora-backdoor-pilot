"""Builds notebooks/62_exp006_bankcheck.ipynb (EXP-006 Stage 2a on Kaggle T4) from the repo files; nothing is pasted by hand.
Run from the repo root:  python notebooks/make_62_exp006_bankcheck.py
Embeds common/exp6_train.py and common/exp6_bankcheck.py. REQUIRES the private dataset (bank_sample_private.zip, unpacked by Kaggle)
attached with Add data. Run with Save Version -> Save & Run All."""
import hashlib
import json

FILES = [("common/exp6_train.py", "/kaggle/working/common/exp6_train.py"),
         ("common/exp6_bankcheck.py", "/kaggle/working/common/exp6_bankcheck.py")]


def src(path):
    return open(path, encoding="utf-8").read().replace("\r\n", "\n")


def cell(kind, text):
    lines = text.split("\n")
    c = {"cell_type": kind, "metadata": {}, "source": [l + "\n" for l in lines[:-1]] + [lines[-1]]}
    if kind == "code":
        c.update(execution_count=None, outputs=[])
    return c


hashes = {p.split("/")[-1]: hashlib.sha256(src(p).encode()).hexdigest() for p, _ in FILES}
cells = [
    cell("markdown", """# EXP-006 Stage 2a (Kaggle T4): do the WSD authors' own poisoned Qwen2.5-3B adapters carry working backdoors?
Thresholds and reading rules: `tracking/experiments/EXP-006-*.md`, section "Stage 2a" (frozen). Generated by `notebooks/make_62_exp006_bankcheck.py`; nothing to edit.

**Before running:** Kaggle -> Datasets -> New Dataset -> upload `bank_sample_private.zip` (40 adapters, about 30 MB) and keep it **Private** (it holds the authors' adapters; terms unrecorded; do not share). In this notebook: **Add data** -> that dataset. Settings: Accelerator **GPU T4 x2** (one is used), **Internet on**.
**Run with "Save Version" -> "Save & Run All".** It measures attack success of 30 poisoned and 10 benign bank adapters on the same 50 held-out prompts as our own adapters; then it writes `bankcheck/summary.json`, `records.jsonl` and a zip. Download the zip from the version's Output tab."""),
    cell("code", "# Install. No kernel restart needed: the check runs in a fresh python process (last cell).\n!pip -q install -U transformers accelerate\n!pip -q install peft datasets\n!pip -q uninstall -y torchao\n!mkdir -p /kaggle/working/common"),
]
for path, dest in FILES:
    cells.append(cell("code", f"%%writefile {dest}\n{src(path).rstrip()}"))
cells.append(cell("code", f"""import json
CONFIG = {{"experiment": "EXP-006 Stage 2a", "who": "aarush", "sha256_embedded_files": {json.dumps(hashes)}}}
json.dump(CONFIG, open('/kaggle/working/exp6_bankcheck_config.json', 'w'))
print(open('/kaggle/working/exp6_bankcheck_config.json').read())
import glob
print('attached manifest:', glob.glob('/kaggle/input/**/bank_sample/manifest.csv', recursive=True))"""))
cells.append(cell("markdown", "## Check the adapters (about a minute or two each on a T4; unmeasured), then summary and zip"))
cells.append(cell("code", "!python /kaggle/working/common/exp6_bankcheck.py eval /kaggle/working/exp6_bankcheck_config.json"))
nb = {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}, "language_info": {"name": "python"}},
      "nbformat": 4, "nbformat_minor": 4}
json.dump(nb, open("notebooks/62_exp006_bankcheck.ipynb", "w", encoding="utf-8"), indent=1)
print("wrote notebooks/62_exp006_bankcheck.ipynb with", len(cells), "cells; hashes:", hashes)
