# -*- coding: utf-8 -*-
"""Generates notebooks/67_exp009_template_clean_controls.ipynb (Arm T) and notebooks/68_exp009_template_full_clean_controls.ipynb
(Arm F, run only if the EXP-009 ladder says so) from notebooks/66_exp008_recipe_matched_clean_controls.ipynb: same structure
(install cell, embedded exp6_penalty.py and ref_stats_bank_benign.json unchanged), the embedded exp6_train.py replaced with the
current common/exp6_train.py (now with a text_format override), and a new CONFIG cell. Same convention as 65/66: do not edit the
generated notebooks by hand except the CONFIG cell.
Run: cd notebooks && python make_67_exp009_template.py
"""
import hashlib
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC_NB = os.path.join(HERE, "66_exp008_recipe_matched_clean_controls.ipynb")
TRAIN_PY = os.path.join(HERE, "..", "common", "exp6_train.py")

ARMS = {
    "T": {"out": "67_exp009_template_clean_controls.ipynb", "group": "bench_ctrl_tmpl",
          "overrides": {"text_format": "alpaca_template"},
          "note": "ONE variable differs from the original `bench_ctrl` batch: the clean text format "
                  "(`### Instruction: ... / ### Response: ...`, the authors' benign Alpaca template, instead of plain `instruction output`). "
                  "1000 rows, 256 tokens, dropout 0.0, no accumulation as in `bench_ctrl`.",
          "title": "EXP-009 Arm T (Kaggle T4): template-matched clean controls"},
    "F": {"out": "68_exp009_template_full_clean_controls.ipynb", "group": "bench_ctrl_tmpl_full",
          "overrides": {"text_format": "alpaca_template", "n_train": 3000, "max_length": 512, "dropout": 0.05, "grad_accum": 4},
          "note": "**Run this only if the EXP-009 file says Arm F runs (Arm T read partial or not supported).** The template plus the "
                  "EXP-008 settings: 3000 rows, 512 tokens, dropout 0.05, gradient accumulation 4.",
          "title": "EXP-009 Arm F (Kaggle T4): template plus matched settings, clean controls"},
}


def sha256_text(s):
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def code_cell(src):
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": src.splitlines(keepends=True)}


def md_cell(src):
    return {"cell_type": "markdown", "metadata": {}, "source": src.splitlines(keepends=True)}


def build(arm):
    a = ARMS[arm]
    nb = json.load(open(SRC_NB, encoding="utf-8"))
    cells = nb["cells"]
    assert cells[3]["source"][0].startswith("%%writefile") and "exp6_train.py" in cells[3]["source"][0]
    assert cells[2]["source"][0].startswith("%%writefile") and "exp6_penalty.py" in cells[2]["source"][0]
    train_src = open(TRAIN_PY, encoding="utf-8").read()
    penalty_sha = sha256_text("".join(cells[2]["source"]).split("\n", 1)[1])
    ref_sha = sha256_text("".join(cells[4]["source"]).split("\n", 1)[1])
    cells[3] = code_cell(f"%%writefile /kaggle/working/common/exp6_train.py\n{train_src}")
    train_sha = sha256_text(train_src)
    cells[0] = md_cell(
        f"# {a['title']}\n"
        "Thresholds and plan: `tracking/experiments/EXP-009-*.md` (written before any run). Generated by "
        "`notebooks/make_67_exp009_template.py` from notebook 66; do not edit by hand except the CONFIG cell.\n\n"
        "**Run with \"Save Version\" -> \"Save & Run All\", not interactively.** Settings: Accelerator **GPU T4 x2** "
        "(one is used), **Internet on**, nothing under Add data.\n\n"
        f"{a['note']}\n\n"
        "Six clean adapters, seeds 0 to 5 (the same seeds, hence the same training rows, as the original `bench_ctrl` batch), "
        "0% poison. Because the evaluation prompts are plain (not in the template), attack success and false trigger are sanity "
        "checks only; expect 0.00 and no `HACKED`.\n\n"
        "After downloading the zip: register the adapters, then score once with `common/exp9_score.py` "
        f"(argument `{arm}`) against the frozen `D_A`, as written in the EXP-009 file."
    )
    code_sha = {"exp6_penalty.py": penalty_sha, "exp6_train.py": train_sha, "ref_stats_bank_benign.json": ref_sha}
    ov = json.dumps(a["overrides"])
    config_src = (
        "# ---- CONFIG: the only cell you edit ----\n"
        f"GROUP = '{a['group']}'   # EXP-009 arm {arm}\n"
        "SEEDS = [0, 1, 2, 3, 4, 5]     # same seeds as the original bench_ctrl batch\n"
        "LAMS = [1, 10, 100]            # unused for this group; kept for CONFIG-shape compatibility with 65/66\n"
        "PR = 0.05                      # ignored for a clean group (no row is poisoned)\n"
        "WHO = 'aarush'\n"
        "EXPERIMENT = 'EXP-009'\n"
        f"RECIPE_OVERRIDES = {ov}\n"
        f"CODE = {{'experiment': EXPERIMENT, 'sha256_embedded_files': {json.dumps(code_sha)}}}\n"
        "# ----------------------------------------\n"
        "import json\n"
        "json.dump({'group': GROUP, 'seeds': SEEDS, 'lams': LAMS, 'pr': PR, 'who': WHO, 'code': CODE,\n"
        "           'experiment': EXPERIMENT, 'recipe_overrides': RECIPE_OVERRIDES},\n"
        "          open('/kaggle/working/exp6_config.json', 'w'))\n"
        "print(open('/kaggle/working/exp6_config.json').read())\n"
    )
    cells[5] = code_cell(config_src)
    cells[6] = md_cell(
        "## Train and evaluate, then SHA256SUMS.txt and a zip in `/kaggle/working`\n"
        "Six clean adapters. A crash gets a run record with status `failed` and the queue continues; a failed seed is rerun with the "
        "same seed, never replaced. Download the zip at once."
    )
    nb["cells"] = cells
    out = os.path.join(HERE, a["out"])
    json.dump(nb, open(out, "w", encoding="utf-8"), indent=1)
    print("wrote", out, "| exp6_train.py sha256:", train_sha)


if __name__ == "__main__":
    for arm in ARMS:
        build(arm)
