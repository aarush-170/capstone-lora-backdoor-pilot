import hashlib
import json

FILES = [("common/exp6_penalty.py", "/kaggle/working/common/exp6_penalty.py"),
         ("common/exp6_train.py", "/kaggle/working/common/exp6_train.py"),
         ("tracking/experiments/EXP-006/ref_stats_bank_benign.json", "/kaggle/working/common/ref_stats_bank_benign.json")]


def src(path):
    return open(path, encoding="utf-8").read().replace("\r\n", "\n")


def sha(path):
    return hashlib.sha256(src(path).encode()).hexdigest()


def cell(kind, text):
    lines = text.split("\n")
    c = {"cell_type": kind, "metadata": {}, "source": [l + "\n" for l in lines[:-1]] + [lines[-1]]}
    if kind == "code":
        c.update(execution_count=None, outputs=[])
    return c


hashes = {p.split("/")[-1]: sha(p) for p, _ in FILES}
cells = [
    cell("markdown", """# EXP-006 Stage 2 (Kaggle T4): the WSD authors' poisoning recipe on Qwen2.5-3B + our white-box penalty
Thresholds and plan: `tracking/experiments/EXP-006-*.md` (frozen). Generated by `notebooks/make_60_exp006_stage2.py`; do not edit by hand except the CONFIG cell.

**Run with "Save Version" -> "Save & Run All", not interactively** (interactive sessions were lost to the idle prompt in EXP-004). Settings: Accelerator **GPU T4 x2** (one is used), **Internet on**, nothing under Add data.
Order: 1) `GROUP = 'smoke'` first (timing with and without the penalty, then one full poisoned adapter with the attack-success check); read `smoke_timing.json` and the printed attack success BEFORE choosing the batch. 2) then `bench_ctrl`, `bd_ctrl`, `evasive` as set in the plan. Download the zip from the version's Output tab straight away."""),
    cell("code", "# Install. No kernel restart needed: training runs in a fresh python process (last cell).\n!pip -q install -U transformers accelerate\n!pip -q install peft datasets\n!pip -q uninstall -y torchao  # peft refuses LoRA with an old torchao; we do not use it\n!mkdir -p /kaggle/working/common"),
]
for path, dest in FILES:
    cells.append(cell("code", f"%%writefile {dest}\n{src(path).rstrip()}"))
cells.append(cell("code", f"""# ---- CONFIG: the only cell you edit ----
GROUP = 'smoke'        # 'smoke' | 'bench_ctrl' | 'bd_ctrl' | 'evasive'
SEEDS = [0, 1, 2]      # bench_ctrl / bd_ctrl: 0-5 ; evasive: 0-2 (ignored for smoke)
LAMS = [1, 10, 100]    # evasive only; drop 1 first if time runs short (plan cut order)
PR = 0.05              # poisoned fraction (plan fallback ladder: 0.10 once, decided at the smoke test, never after detector scores)
WHO = 'aarush'
CODE = {json.dumps({"experiment": "EXP-006", "sha256_embedded_files": hashes})}
# ----------------------------------------
import json
json.dump({{'group': GROUP, 'seeds': SEEDS, 'lams': LAMS, 'pr': PR, 'who': WHO, 'code': CODE}}, open('/kaggle/working/exp6_config.json', 'w'))
print(open('/kaggle/working/exp6_config.json').read())"""))
cells.append(cell("markdown", "## Train and evaluate (about the time per adapter the smoke test reports), then SHA256SUMS.txt and a zip in `/kaggle/working`\nA `bd_ctrl` or `evasive` adapter below 0.80 attack success is a RESULT (record kept), not a discard. A crash gets a run record with status `failed` and the queue continues."))
cells.append(cell("code", "!python /kaggle/working/common/exp6_train.py /kaggle/working/exp6_config.json"))
nb = {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}, "language_info": {"name": "python"}},
      "nbformat": 4, "nbformat_minor": 4}
json.dump(nb, open("notebooks/60_exp006_stage2.ipynb", "w", encoding="utf-8"), indent=1)
print("wrote notebooks/60_exp006_stage2.ipynb with", len(cells), "cells; embedded file hashes:", hashes)
